"""Real OpenCode/tool execution with a scripted local HTTP fixture, NOT a model.

No paid API or benchmark scientific score is generated by this test.
"""
import argparse,copy,hashlib,json,os,pathlib,subprocess,sys,threading
from http.server import BaseHTTPRequestHandler,ThreadingHTTPServer
ROOT=pathlib.Path(__file__).resolve().parents[1]
TEXT='scibench-local-release-transport-test';EXPECTED=hashlib.sha256(TEXT.encode()).hexdigest()
COMMAND="python -c \"import hashlib,networkx; print(hashlib.sha256(b'"+TEXT+"').hexdigest(), networkx.__version__)\""

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--output',required=True);a=ap.parse_args()
    out=pathlib.Path(a.output).resolve();out.mkdir(parents=True,exist_ok=True);seen=[]
    public=[json.loads(x) for x in (ROOT/'data/benchmark_288_public.jsonl').read_text().splitlines()][0]
    class Fixture(BaseHTTPRequestHandler):
        def log_message(self,*args):pass
        def do_POST(self):
            body=json.loads(self.rfile.read(int(self.headers['Content-Length'])));seen.append((self.path,body))
            responses=self.path.endswith('/responses')
            if responses:
                items=body['input'];continued=any(i.get('type')=='function_call_output' for i in items)
                assert items[:2]==public['messages']
                if continued:
                    assert EXPECTED in next(i['output'] for i in items if i.get('type')=='function_call_output')
                    output=[{'type':'message','role':'assistant','content':[{'type':'output_text','text':'PROTOCOL FIXTURE '+EXPECTED+' networkx 3.4.2'}]}]
                else:
                    output=[{'type':'function_call','id':'fc_fixture','call_id':'call_fixture','name':body['tools'][0]['name'],'arguments':json.dumps({'command':COMMAND})}]
                events=[{'type':'response.completed','response':{'id':'response_fixture','model':body['model'],'status':'completed','output':output,'usage':{'input_tokens':10,'output_tokens':5,'total_tokens':15}}}]
            else:
                assert body['messages'][:2]==public['messages']
                continued=any(m['role']=='tool' for m in body['messages'])
                if continued:
                    assert EXPECTED in next(m['content'] for m in body['messages'] if m['role']=='tool')
                    delta={'role':'assistant','content':'PROTOCOL FIXTURE '+EXPECTED+' networkx 3.4.2'};finish='stop'
                else:
                    delta={'role':'assistant','content':'','tool_calls':[{'index':0,'id':'call_fixture','type':'function','function':{'name':body['tools'][0]['function']['name'],'arguments':json.dumps({'command':COMMAND})}}]};finish='tool_calls'
                events=[{'id':'chat_fixture','object':'chat.completion.chunk','model':body['model'],'choices':[{'index':0,'delta':delta,'finish_reason':None}]},{'id':'chat_fixture','object':'chat.completion.chunk','model':body['model'],'choices':[{'index':0,'delta':{},'finish_reason':finish}],'usage':{'prompt_tokens':10,'completion_tokens':5,'total_tokens':15}}]
            raw=(''.join('data: '+json.dumps(e)+'\n\n' for e in events)+'data: [DONE]\n\n').encode()
            self.send_response(200);self.send_header('Content-Type','text/event-stream');self.send_header('Content-Length',str(len(raw)));self.end_headers();self.wfile.write(raw)
    server=ThreadingHTTPServer(('127.0.0.1',0),Fixture);thread=threading.Thread(target=server.serve_forever,daemon=True);thread.start();report=[]
    try:
        for transport in ('chat_completions','responses','local_openai_compatible'):
            cfg=json.loads((ROOT/'configs/chat.json').read_text());cfg['model'].update(name='PROTOCOL_FIXTURE_NOT_A_MODEL',base_url='http://127.0.0.1:'+str(server.server_port)+'/v1',api_key_env='SCIBENCH_TEST_KEY',transport='responses' if transport=='responses' else 'chat_completions')
            config=out/(transport+'.json');config.write_text(json.dumps(cfg));dest=out/transport
            cmd=[str(ROOT/'.runtime/venv/bin/scibench'),'eval','--model',cfg['model']['name'],'--config',str(config),'--output',str(dest),'--smoke','--limit','1','--concurrency','1']
            env=dict(os.environ,SCIBENCH_TEST_KEY='TEST_ONLY_NOT_A_REAL_KEY')
            with (out/(transport+'.log')).open('w') as log:subprocess.run(cmd,cwd=ROOT,env=env,stdout=log,stderr=subprocess.STDOUT,check=True)
            row=json.loads((dest/'logs'/public['id']/'trajectory.json').read_text());preds=[json.loads(x) for x in (dest/'predictions.jsonl').read_text().splitlines()]
            assert row['status']=='success' and row['agent_model_calls']==2 and len(row['tool_calls'])==1,(transport,row)
            assert EXPECTED in preds[0]['prediction'] and set(preds[0])=={'id','prediction'}
            tool=json.loads(row['tool_calls'][0]['output']);assert tool['status']=='ok' and tool['exit_code']==0 and '3.4.2' in tool['output']
            before=len(seen)
            with (out/(transport+'_resume.log')).open('w') as log:subprocess.run(cmd+['--resume'],cwd=ROOT,env=env,stdout=log,stderr=subprocess.STDOUT,check=True)
            assert len(seen)==before
            report.append({'transport':transport,'pass':True,'real_opencode':True,'real_scientific_shell':True,'http_fixture_not_model':True,'model_continuation_rounds':2,'resume_additional_calls':0,'scored':False})
    finally:server.shutdown();server.server_close()
    result={'pass':True,'tests':report,'paid_api_calls':0,'historical_solver_reruns':0,'scope':'Scripted HTTP fixture + actual OpenCode and bubblewrap tool, not provider model capability validation'}
    (out/'TRANSPORT_REPORT.json').write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(result))
if __name__=='__main__':main()
